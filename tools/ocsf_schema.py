"""Refresh the vendored OCSF Detection Finding attribute requirements.

SARIF ships its schema as a document, so ``tests/fixtures/sarif/`` holds the
genuine OASIS file and the tests validate against it directly. OCSF does not:
its schema is served from ``schema.ocsf.io`` and there is no official
distributable JSON Schema for a class. The vendored file is therefore a
transcription, and this tool is how it stops being one by hand.

Run ``python -m tools.ocsf_schema --refresh`` with network access to rewrite
``tests/fixtures/ocsf/detection_finding_<version>.json`` from the live class
definition. It fails loudly rather than writing a partial or guessed file when
the endpoint is unreachable, so an offline run can never silently downgrade
the fixture into something weaker than what is already committed.

``--check`` reports whether the vendored file matches the version the reporter
emits, which is what CI needs: a version bump in the reporter must not leave
the requirements behind.
"""

from __future__ import annotations

import argparse
import json
import sys
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any

from shadowscan.reporters.ocsf import _OCSF_VERSION

FIXTURES = Path(__file__).resolve().parent.parent / "tests" / "fixtures" / "ocsf"
CLASS_NAME = "detection_finding"
SOURCE = "https://schema.ocsf.io/{version}/classes/{cls}"
TIMEOUT_SECONDS = 30


def fixture_path(version: str = _OCSF_VERSION) -> Path:
    return FIXTURES / f"{CLASS_NAME}_{version}.json"


def load(version: str = _OCSF_VERSION) -> dict[str, Any]:
    """The vendored requirements for *version*, or raise FileNotFoundError."""
    data: dict[str, Any] = json.loads(fixture_path(version).read_text(encoding="utf-8"))
    return data


def _fetch(version: str) -> dict[str, Any]:
    url = SOURCE.format(version=version, cls=CLASS_NAME)
    request = urllib.request.Request(url, headers={"Accept": "application/json"})
    with urllib.request.urlopen(request, timeout=TIMEOUT_SECONDS) as response:
        payload: dict[str, Any] = json.loads(response.read().decode("utf-8"))
    return payload


def _requirements(live: dict[str, Any], version: str) -> dict[str, Any]:
    """Reduce a live class definition to the requirement manifest the tests read."""
    attributes = live.get("attributes") or {}
    if not isinstance(attributes, dict) or not attributes:
        raise ValueError("class definition carried no attributes; refusing to write a weaker fixture")
    required = sorted(k for k, v in attributes.items() if v.get("requirement") == "required")
    recommended = sorted(k for k, v in attributes.items() if v.get("requirement") == "recommended")
    if "time" not in required:
        raise ValueError("'time' is not required in the fetched definition; verify the source before writing")
    types = {k: v["type"] for k, v in sorted(attributes.items()) if v.get("type")}
    enums = {
        k: sorted(int(e) for e in v["enum"])
        for k, v in sorted(attributes.items())
        if isinstance(v.get("enum"), dict) and all(str(e).lstrip("-").isdigit() for e in v["enum"])
    }
    return {
        "_provenance": {
            "description": (
                f"Attribute requirements for the OCSF {live.get('caption', 'Detection Finding')} "
                f"class (uid {live.get('uid')}), fetched from the OCSF schema server."
            ),
            "source": SOURCE.format(version=version, cls=CLASS_NAME),
            "transcribed": False,
            "note": "Generated by tools/ocsf_schema.py --refresh. Do not edit by hand.",
            "ocsf_version": version,
            "class_uid": live.get("uid"),
            "class_name": live.get("caption"),
        },
        "required": required,
        "recommended": recommended,
        "types": types,
        "enums": enums,
        "finding_info_required": ["title", "uid"],
        "metadata_required": ["product", "version"],
        "product_required": ["name", "vendor_name"],
    }


def refresh(version: str = _OCSF_VERSION) -> int:
    try:
        live = _fetch(version)
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        print(f"could not reach the OCSF schema server: {exc}", file=sys.stderr)
        print("the committed fixture is unchanged", file=sys.stderr)
        return 2
    try:
        manifest = _requirements(live, version)
    except (KeyError, ValueError) as exc:
        print(f"refusing to write the fixture: {exc}", file=sys.stderr)
        return 3
    target = fixture_path(version)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(manifest, indent=2, sort_keys=False) + "\n", encoding="utf-8")
    print(f"wrote {target}")
    return 0


def check(version: str = _OCSF_VERSION) -> int:
    path = fixture_path(version)
    if not path.exists():
        print(
            f"no vendored OCSF requirements for {version}: expected {path}.\n"
            "The reporter's _OCSF_VERSION changed without the fixture. Run "
            "`python -m tools.ocsf_schema --refresh` with network access.",
            file=sys.stderr,
        )
        return 1
    recorded = load(version)["_provenance"]["ocsf_version"]
    if recorded != version:
        print(f"fixture records OCSF {recorded}, reporter emits {version}", file=sys.stderr)
        return 1
    print(f"OCSF {version} requirements present at {path}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--refresh", action="store_true", help="fetch and rewrite the vendored file")
    group.add_argument("--check", action="store_true", help="verify the fixture matches the reporter")
    parser.add_argument("--version", default=_OCSF_VERSION)
    args = parser.parse_args(argv)
    return refresh(args.version) if args.refresh else check(args.version)


if __name__ == "__main__":
    raise SystemExit(main())
